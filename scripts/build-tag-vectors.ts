// Builds the tag phrase vectors for search by meaning from the desktop app's prompts.
// Run: node scripts/build-tag-vectors.ts <lumo-desktop>/src/main/tags/tag-vectors.json
// Writes app/assets/tag-vectors.bin (LSV1, ids = index in TAG_VECTOR_SLUGS) and app/utils/tag-vector-slugs.ts.
// Per slug: the mean of its prompt vectors (prompt ensembling), unit length; int8 like the photo file (~76 KB).
import { readFileSync, writeFileSync } from 'node:fs'
import { encodeLSV1, meanVector, parseLSV1, decodeRow } from '../app/utils/vectors.ts'

const src = process.argv[2]
if (!src) throw new Error('usage: node scripts/build-tag-vectors.ts <tag-vectors.json>')
const j = JSON.parse(readFileSync(src, 'utf8')) as { model: string; dim: number; logitScale: number; logitBias: number; tags: { slug: string; vecs: string[] }[] }
const f32 = (b64: string) => { const b = Buffer.from(b64, 'base64'); return new Float32Array(b.buffer.slice(b.byteOffset, b.byteOffset + j.dim * 4)) }
const items = j.tags.map((t, i) => ({ id: i, vec: meanVector(t.vecs.map(f32)) }))
// Same tag as the photo files the desktop app writes: the worker only mixes vectors with the same tag.
const buf = encodeLSV1(items, 'siglip2-b16-q8', j.dim)
const f = parseLSV1(buf)
let worst = 1
items.forEach((it, i) => { const d = decodeRow(f, i); let c = 0; for (let k = 0; k < j.dim; k++) c += d[k]! * it.vec[k]!; worst = Math.min(worst, c) })
writeFileSync(new URL('../app/assets/tag-vectors.bin', import.meta.url), new Uint8Array(buf))
writeFileSync(new URL('../app/utils/tag-vector-slugs.ts', import.meta.url), `// Generated by scripts/build-tag-vectors.ts from the desktop's ${j.model} prompts. Do not edit.
// Row i of app/assets/tag-vectors.bin is TAG_VECTOR_SLUGS[i].
// The desktop scores a tag as logit = LOGIT_SCALE * cos + LOGIT_BIAS (SigLIP's sigmoid head).
export const TAG_VECTOR_SLUGS = ${JSON.stringify(j.tags.map(t => t.slug))}
export const LOGIT_SCALE = ${j.logitScale}
export const LOGIT_BIAS = ${j.logitBias}
`)
console.log({ slugs: items.length, bytes: buf.byteLength, worstCos: worst })
